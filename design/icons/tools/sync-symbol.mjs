// Copies design/icons/spec-7-patch.svg into the #patch <symbol> in public/index.html.
// Keeps the sprite file and the artwork in sync; idempotent.
// Run: node design/icons/tools/sync-symbol.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const here = fileURLToPath(new URL('.', import.meta.url));
const svgPath = here + '../spec-7-patch.svg';
const htmlPath = here + '../../../public/index.html';

const svg = readFileSync(svgPath, 'utf8');
const body = svg
  .replace(/^[\s\S]*?<svg[^>]*>/, '')
  .replace(/<\/svg>\s*$/, '')
  .replace(/^\s*<title>[\s\S]*?<\/title>\s*$/m, '')
  .replace(/^\n+/, '')
  .replace(/\s+$/, '')
  .split('\n')
  .map((l) => '  ' + l.trimEnd())
  .join('\n');

const html = readFileSync(htmlPath, 'utf8');
const re = /(<symbol id="patch" viewBox="0 0 120 120">\n)[\s\S]*?(\n  <\/symbol>)/;
if (!re.test(html)) throw new Error('patch symbol not found in index.html');
const next = html.replace(re, `$1    <!-- generated by design/icons/tools/gen-patch.mjs — do not hand-edit -->\n${body}$2`);
writeFileSync(htmlPath, next);
console.log('patch symbol synced (' + body.split('\n').length + ' lines)');
